/** 글에서 낱말을 뽑는다. 한글은 조사·어미를 대충 떼고, 영문·숫자섞임은 그대로. */
export function 낱말뽑기(글, { 최대 = 400 } = {}) {
  const 낱말 = [];
  const 한글 = String(글).match(/[가-힣]{2,}/g) || [];
  for (let w of 한글) {
    // 붙은 조사 떼기 (여러 겹까지 두 번)
    for (let i = 0; i < 2; i++)
      w = w.replace(/(에서는|에서도|으로는|에게는|이라는|라는|하는|했던|하던|이라고|라고|에서|으로|에게|까지|부터|이나|처럼|보다|들의|들을|들이|이다|였다|한다|된다|하고|하며|의|은|는|이|가|을|를|에|로|와|과|도|만)$/, '');
    if (w.length >= 2 && !흔한말.has(w)) 낱말.push(w);
    if (낱말.length >= 최대) break;
  }
  const 영문 = String(글).match(/\b[A-Za-z][A-Za-z0-9.\-]{1,}\b/g) || [];
  for (const w of 영문) {
    const t = w.replace(/[.\-]+$/, '');
    if (/\.(com|net|org|kr|io|co|me|html?|jpe?g|png|gif)$/i.test(t)) continue;   // 주소·파일명은 주제가 아니다
    if (t.length >= 2 && !/^(the|and|for|with|this|that|http|https|www|com|net|org|jpg|png|html)$/i.test(t)) 낱말.push(t.toUpperCase().length <= 5 ? t.toUpperCase() : t);
    if (낱말.length >= 최대 + 100) break;
  }
  return 낱말;
}

/* ───────── 자료 하나 ───────── */

const 사진태그 = /!\[[^\]]*\]\(|<img\b/gi;

/** 파일 하나에서 제목·날짜·발췌·낱말을 뽑는다.
 *  @param {{이름:string, 글?:string, 이진?:boolean, 크기?:number}} 파일 */
export function 자료정리(파일, 번호 = 0) {
  const 이름 = 파일.이름 || '';
  const 확장 = (이름.match(/\.([^.]+)$/) || [, ''])[1].toLowerCase();
  const 바닥 = 이름.split('/').pop();
  const 종류 = /^(jpg|jpeg|png|gif|webp|bmp|avif|svg)$/.test(확장) ? '사진'
             : /^(md|txt|html|htm)$/.test(확장) ? '글' : '문서';

  // 날짜: 파일 이름 앞머리 → 글 안 날짜 표시
  let 날짜 = (바닥.match(/(20\d\d)[-_.](\d{1,2})[-_.](\d{1,2})/) || []).slice(1, 4);
  const 글 = 파일.글 || '';
  if (!날짜.length) 날짜 = (글.slice(0, 2000).match(/(20\d\d)[-.년\s]+(\d{1,2})[-.월\s]+(\d{1,2})/) || []).slice(1, 4);
  const 날짜문 = 날짜.length === 3 ? `${날짜[0]}-${String(날짜[1]).padStart(2, '0')}-${String(날짜[2]).padStart(2, '0')}` : '';

  // 제목: md 앞머리 제목: → 첫 # → <title>/<h1> → 파일 이름
  let 제목 = '';
  const 앞머리 = 글.match(/^\s*제목\s*:\s*(.+)$/m);
  if (앞머리) 제목 = 앞머리[1].trim();
  if (!제목) { const h = 글.match(/^#\s+(.+)$/m); if (h) 제목 = h[1].trim(); }
  if (!제목) { const h = 글.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || 글.match(/<title[^>]*>([\s\S]*?)<\/title>/i); if (h) 제목 = 글벗기기(h[1]); }
  if (!제목) 제목 = 바닥.replace(/\.[^.]+$/, '').replace(/^\d{4}[-_.]\d{1,2}[-_.]\d{1,2}[-_]?/, '').replace(/^\d+[!_.\-\s]*/, '').replace(/_/g, ' ').trim();
  제목 = 제목.replace(/\s+/g, ' ').slice(0, 120) || 바닥;

  const 본문 = 종류 === '글' ? 글벗기기(글) : '';
  const 사진수 = (글.match(사진태그) || []).length;

  return {
    번호, 파일: 이름, 제목, 날짜: 날짜문, 종류, 확장,
    글자수: 본문.length,
    사진수,
    크기: 파일.크기 ?? (글 ? 글.length : 0),
    발췌: 본문.slice(0, 400),
    // 낱말 = 이 자료가 무엇에 관한 것인가(본문까지). 제목낱말 = 주제 씨앗 후보(제목만).
    // 제목은 명사 위주라 깨끗하고, 본문은 동사·어미가 섞여 주제 이름으로 못 쓴다.
    낱말: 종류 === '글' ? 낱말뽑기(제목 + ' ' + 본문.slice(0, 4000)) : 낱말뽑기(제목),
    제목낱말: 낱말뽑기(제목),
  };
}

/** 마크다운·HTML 껍데기를 벗겨 사람 문장만 남긴다 (조판이 아니라 세기용) */
export function 글벗기기(s) {
  return String(s)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ').replace(/&amp;/gi, '&').replace(/&lt;/gi, '<').replace(/&gt;/gi, '>')
    .replace(/&#x?[0-9a-f]+;/gi, ' ')
    .replace(/^---[\s\S]*?---/m, ' ')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[#*_>`~|]/g, ' ')
    .replace(/https?:\/\/\S+/g, ' ')
    .replace(/\s+/g, ' ').trim();
}

/* ───────── 전체 모양 ───────── */

export function 전체보기(자료들) {
  const 글들 = 자료들.filter(a => a.종류 === '글');
  const 날짜있음 = 자료들.filter(a => a.날짜).map(a => a.날짜).sort();
  const 해별 = {};
  for (const d of 날짜있음) { const y = d.slice(0, 4); 해별[y] = (해별[y] || 0) + 1; }
  const 길이 = 글들.map(a => a.글자수).sort((a, b) => a - b);
  const 가운데 = 길이.length ? 길이[Math.floor(길이.length / 2)] : 0;
  const 사진합 = 자료들.reduce((s, a) => s + a.사진수, 0) + 자료들.filter(a => a.종류 === '사진').length;
  const 종류별 = {};
  for (const a of 자료들) 종류별[a.종류] = (종류별[a.종류] || 0) + 1;
  const 확장별 = {};
  for (const a of 자료들) 확장별[a.확장] = (확장별[a.확장] || 0) + 1;

  return {
    자료수: 자료들.length,
    종류별, 확장별,
    글수: 글들.length,
    날짜있는수: 날짜있음.length,
    처음날짜: 날짜있음[0] || '', 끝날짜: 날짜있음[날짜있음.length - 1] || '',
    해별,
    해수: Object.keys(해별).length,
    글자수가운데: 가운데,
    글자수평균: 길이.length ? Math.round(길이.reduce((a, b) => a + b, 0) / 길이.length) : 0,
    짧은글수: 글들.filter(a => a.글자수 < 400).length,
    긴글수: 글들.filter(a => a.글자수 > 2500).length,
    사진합,
    자료당사진: 자료들.length ? Math.round(사진합 / 자료들.length * 10) / 10 : 0,
    사진많은수: 자료들.filter(a => a.사진수 >= 5).length,
  };
}

/* ───────── 주제 갈래 스스로 찾기 (사전 없이) ───────── */

/**
 * 낱말 빈도로 주제 후보를 만들고, 가장 많이 덮는 것부터 골라 묶는다.
 * 손으로 적은 주제 사전이 없으므로 자료가 바뀌면 갈래도 바뀐다.
 * @returns {{갈래:Array, 미분류:Array, 흔한낱말:Array}}
 */
export function 갈래뽑기(자료들, { 최대갈래 = 12, 최소건수 = 3 } = {}) {
  const N = 자료들.length;
  const 하한 = Math.max(최소건수, Math.round(N * 0.004));
  // 너무 흔한 말은 주제가 못 된다. 자료 넷 중 하나꼴로 나오면 그건 이 폴더의 배경말이지 갈래가 아니다.
  const 상한 = Math.max(하한 + 1, Math.round(N * 0.15));

  // 낱말 → 그 낱말이 나온 자료 번호들 (본문까지 — 어디에 속하는가를 볼 때 씀)
  const 어디에 = new Map();
  자료들.forEach((a, i) => {
    for (const w of new Set(a.낱말)) {
      if (!어디에.has(w)) 어디에.set(w, []);
      어디에.get(w).push(i);
    }
  });
  // 제목에 몇 번 나왔나 (주제 씨앗이 될 자격)
  const 제목에 = new Map();
  자료들.forEach(a => { for (const w of new Set(a.제목낱말 || [])) 제목에.set(w, (제목에.get(w) || 0) + 1); });

  const 후보 = [...어디에.entries()]
    .filter(([w, xs]) => xs.length >= 하한 && xs.length <= 상한 && w.length >= 2
                      && (제목에.get(w) || 0) >= 2)     // 제목에 두 번은 나와야 주제로 인정
    .map(([낱말, 자료번호]) => ({ 낱말, 자료번호, 제목수: 제목에.get(낱말) }));

  const 남음 = new Set(자료들.map((_, i) => i));
  const 갈래 = [];
  for (let 판 = 0; 판 < 최대갈래 && 남음.size; 판++) {
    let 최고 = null;
    for (const c of 후보) {
      const 새것 = c.자료번호.filter(i => 남음.has(i));
      if (새것.length < 하한) continue;
      // 점수 = 새로 덮는 수 × 낱말 길이 보정(긴 낱말이 더 구체적) × 제목에 나온 비율 보정
      //        (본문에만 스치는 말보다, 제목에 걸린 말이 진짜 주제다)
      const 제목비 = Math.min(1, (c.제목수 || 0) / Math.max(1, c.자료번호.length));
      const 점수 = 새것.length * (1 + Math.min(c.낱말.length, 6) / 12) * (0.5 + 제목비);
      if (!최고 || 점수 > 최고.점수) 최고 = { ...c, 새것, 점수 };
    }
    if (!최고) break;

    // 이 묶음 안에서 같이 자주 나오는 낱말 = 곁낱말 (이름 짓기·설명용)
    const 같이 = new Map();
    for (const i of 최고.새것) for (const w of new Set(자료들[i].낱말)) if (w !== 최고.낱말) 같이.set(w, (같이.get(w) || 0) + 1);
    const 곁낱말 = [...같이.entries()]
      .filter(([w, n]) => n >= Math.max(2, Math.round(최고.새것.length * 0.25))
                       && (어디에.get(w) || []).length <= 상한)   // 폴더 전체의 배경말은 설명이 못 된다
      .sort((a, b) => b[1] - a[1]).slice(0, 8).map(([w, n]) => ({ 낱말: w, 건수: n }));

    갈래.push({
      이름: 최고.낱말,                        // 임시 이름 — 2층 AI 가 제대로 짓는다
      씨앗낱말: 최고.낱말,
      곁낱말,
      자료번호: 최고.새것,
      건수: 최고.새것.length,
      까닭: `「${최고.낱말}」 이 제목·본문에 나오는 자료 ${최고.새것.length}건`,
    });
    for (const i of 최고.새것) 남음.delete(i);
  }

  return {
    갈래,
    미분류: [...남음],
    흔한낱말: [...어디에.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 40).map(([w, xs]) => ({ 낱말: w, 건수: xs.length })),
  };
}

/* ───────── 디자인·배치 추천 ───────── */

/**
 * 자료의 모양을 보고 디자인·배치를 고른다. 왜 골랐는지 항상 붙인다.
 * @param {object} 모양 전체보기() 결과
 * @param {string[]} 있는디자인 디자인/ 폴더에 실제로 있는 이름들
 */
export function 추천(모양, 있는디자인 = []) {
  const 배치점수 = [
    { 이름: '타임라인', 점수: 0, 까닭: [] },
    { 이름: '갤러리', 점수: 0, 까닭: [] },
    { 이름: '바둑판', 점수: 0, 까닭: [] },
    { 이름: '목록', 점수: 0, 까닭: [] },
    { 이름: '잡지', 점수: 0, 까닭: [] },
    { 이름: '나열', 점수: 1, 까닭: ['어느 자료에나 무난한 기본'] },
    { 이름: '슬라이드', 점수: 0, 까닭: [] },
  ];
  const 주기 = (이름, 점, 까닭) => { const b = 배치점수.find(x => x.이름 === 이름); if (b && 점) { b.점수 += 점; b.까닭.push(까닭); } };

  const 날짜비율 = 모양.자료수 ? 모양.날짜있는수 / 모양.자료수 : 0;
  if (날짜비율 > 0.8 && 모양.해수 >= 3) 주기('타임라인', 5, `자료 ${Math.round(날짜비율 * 100)}%에 날짜가 있고 ${모양.해수}해에 걸쳐 있음 — 흐름이 보이는 배치가 맞음`);
  else if (날짜비율 > 0.6) 주기('타임라인', 2, `자료 ${Math.round(날짜비율 * 100)}%에 날짜가 있음`);

  if (모양.자료당사진 >= 3) 주기('갤러리', 5, `자료 한 건에 사진이 평균 ${모양.자료당사진}장 — 사진이 주인공`);
  else if (모양.자료당사진 >= 1) 주기('갤러리', 2, `사진이 자료당 평균 ${모양.자료당사진}장`);
  if (모양.사진많은수 > 모양.자료수 * 0.4) 주기('갤러리', 2, `사진 5장 넘는 자료가 ${모양.사진많은수}건`);

  if (모양.자료수 >= 25) 주기('바둑판', 4, `자료가 ${모양.자료수}건으로 많음 — 한눈에 훑는 카드가 맞음`);
  if (모양.자료수 >= 12 && 모양.자료수 < 25) 주기('바둑판', 2, `자료 ${모양.자료수}건`);

  if (모양.짧은글수 > 모양.글수 * 0.5 && 모양.글수 > 5) 주기('목록', 4, `400자 안 되는 짧은 글이 ${모양.짧은글수}건 — 제목만 늘어놓고 눌러 보는 편이 나음`);
  if (모양.긴글수 > 모양.글수 * 0.4 && 모양.글수 > 3) 주기('잡지', 4, `2500자 넘는 긴 글이 ${모양.긴글수}건 — 읽는 자료라 2단 조판이 어울림`);
  if (모양.자료수 <= 12 && 모양.자료당사진 >= 2) 주기('슬라이드', 3, `자료 ${모양.자료수}건에 사진이 넉넉함 — 한 장씩 넘겨 보기 좋음`);

  배치점수.sort((a, b) => b.점수 - a.점수);

  // 접기
  const 접기 = 모양.자료수 > 8 ? '자동' : '끄기';
  const 접기까닭 = 모양.자료수 > 8 ? `자료 ${모양.자료수}건 — 8건이 넘어 처음엔 접어 둠` : `자료가 ${모양.자료수}건뿐이라 펼쳐 두는 편이 나음`;

  // 디자인
  const 디자인후보 = [];
  const 담기 = (이름, 점, 까닭) => { if (!있는디자인.length || 있는디자인.includes(이름)) 디자인후보.push({ 이름, 점수: 점, 까닭 }); };
  담기('기록장', 3, '기본 — 구글 기록장과 같은 톤이라 다른 기록물과 나란히 놓기 좋음');
  if (모양.긴글수 > 모양.글수 * 0.4) 담기('학술-절제', 4, `긴 글 ${모양.긴글수}건 — 읽는 데 방해가 없는 절제된 톤`);
  if (모양.자료당사진 >= 3) 담기('발표-대형', 3, '사진이 많아 큼직하게 보여 주는 편이 나음');
  if (모양.해수 >= 5) 담기('기록-따뜻', 3, `${모양.해수}해에 걸친 개인 기록 — 따뜻한 톤이 어울림`);
  if (모양.짧은글수 > 모양.글수 * 0.5) 담기('미니멀-흑백', 2, '짧은 메모 위주 — 군더더기 없는 편이 나음');
  if ((모양.확장별?.md || 0) + (모양.확장별?.txt || 0) > 모양.글수 * 0.7) 담기('노트-손글씨', 2, '거의 메모·노트 파일');
  디자인후보.sort((a, b) => b.점수 - a.점수);

  return {
    배치: 배치점수[0].이름,
    배치까닭: 배치점수[0].까닭.length ? 배치점수[0].까닭 : ['특별히 도드라지는 성격이 없어 기본으로 둠'],
    배치다른것: 배치점수.slice(1, 4).filter(b => b.점수 > 0),
    접기, 접기까닭,
    디자인: 디자인후보[0]?.이름 || '기록장',
    디자인까닭: 디자인후보[0]?.까닭 || '기본',
    디자인다른것: 디자인후보.slice(1, 3),
    사진크기: 모양.자료당사진 >= 3 ? '크게' : '보통',
    순서: 모양.날짜있는수 > 모양.자료수 * 0.7 ? '날짜' : '파일명',
    순서까닭: 모양.날짜있는수 > 모양.자료수 * 0.7 ? '거의 모든 자료에 날짜가 있음' : '날짜가 없는 자료가 많아 파일 이름 순',
  };
}
